/**
 * A small seeded PRNG (mulberry32). The particle targets must be reproducible:
 * the same seed gives the same points, so the committed JSON, the static SVGs
 * and the browser's own resampling agree.
 */
export function mulberry32(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
